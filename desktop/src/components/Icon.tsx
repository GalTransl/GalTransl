export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = '1em',
  className,
  style,
  title,
}: {
  name: IconName;
  /** 默认 1em：跟着所在文字的 font-size 走，原地替换 emoji 时不用逐个调大小 */
  size?: number | string;
  className?: string;
  style?: CSSProperties;
  /** 只在图标本身承载语义（旁边没有文字）时才传，否则一律 aria-hidden */
  title?: string;
}) {
  return (
    <svg
      className={className ? `icon ${className}` : 'icon'}
      // 图形本身普遍只占 11–12px；收紧 viewBox 是统一的光学校正，
      // 让 1em 图标与同字号中文的视觉重量相当，同时仍保留防裁切余量。
      viewBox="1 1 14 14"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.3"
      strokeLinecap="round"
      strokeLinejoin="round"
      style={style}
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
    >
      {title ? <title>{title}</title> : null}
      {ICONS[name]}
    </svg>
  );
}
